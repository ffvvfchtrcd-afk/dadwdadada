-- 1. CRIANDO TABELA DE CATEGORIAS
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    status TEXT DEFAULT 'ATIVO',
    hierarquia INTEGER DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. CRIANDO TABELA DE PRODUTOS
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT PRIMARY KEY,
    nome TEXT NOT NULL,
    categoria TEXT,
    descricao TEXT,
    "miniDesc" TEXT,
    "bannerUrl" TEXT,
    status TEXT DEFAULT 'ATIVO',
    "dataCriacao" TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    "dataAtualizacao" TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. CRIANDO TABELA DE VARIAÇÕES (OPÇÕES DE COMPRA / ESTOQUE)
CREATE TABLE IF NOT EXISTS public.variacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "produtoId" BIGINT REFERENCES public.products(id) ON DELETE CASCADE,
    nome TEXT NOT NULL,
    preco NUMERIC NOT NULL,
    "quantidadeStock" INTEGER DEFAULT 0,
    estoque_tipo TEXT DEFAULT 'AUTOMATICA', -- 'AUTOMATICA' ou 'MANUAL'
    "stockData" JSONB DEFAULT '[]'::jsonb, -- Array de strings com as chaves/credenciais
    "imagem_url" TEXT, -- URL da imagem específica da variação (opcional)
    descricao TEXT, -- Descrição específica da variação (opcional)
    status TEXT DEFAULT 'ATIVO',
    "dataAtualizacao" TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. CRIANDO TABELA DE COMPRAS (PEDIDOS)
CREATE TABLE IF NOT EXISTS public.compras (
    id TEXT PRIMARY KEY,
    "userId" UUID,
    "userEmail" TEXT,
    "userName" TEXT,
    total NUMERIC NOT NULL,
    status TEXT DEFAULT 'PENDENTE',
    "deliveryContent" JSONB DEFAULT '[]'::jsonb,
    timeline JSONB DEFAULT '[]'::jsonb,
    cupom TEXT,
    desconto NUMERIC DEFAULT 0,
    items JSONB NOT NULL,
    "dateCreated" TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    "dateDelivered" TIMESTAMP WITH TIME ZONE
);

-- 5. CRIANDO TABELA DE NOTIFICAÇÕES
CREATE TABLE IF NOT EXISTS public.notificacoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL,
    mensagem TEXT NOT NULL,
    tipo TEXT DEFAULT 'info',
    pedido_id TEXT,
    lida BOOLEAN DEFAULT false,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. CRIANDO TABELA DE CONFIGURAÇÕES DO SITE
CREATE TABLE IF NOT EXISTS public.configuracoes (
    id INTEGER PRIMARY KEY DEFAULT 1,
    nome_loja TEXT DEFAULT 'NEXMARKET',
    cupom_ativo BOOLEAN DEFAULT false,
    cupom_codigo TEXT DEFAULT '',
    cupom_porcentagem REAL DEFAULT 0,
    link_discord TEXT DEFAULT '',
    link_suporte TEXT DEFAULT '',
    atualizado_em TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Insere a config padrão se não existir
INSERT INTO public.configuracoes (id, nome_loja, cupom_ativo)
VALUES (1, 'NEXMARKET', false)
ON CONFLICT (id) DO NOTHING;

-- 7. CRIANDO TABELA DE CUPONS (gerenciáveis pelo admin)
CREATE TABLE IF NOT EXISTS public.cupons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo TEXT NOT NULL UNIQUE,
    porcentagem REAL NOT NULL,
    ativo BOOLEAN DEFAULT false,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 8. CRIANDO TABELA DE LOGS DO SISTEMA
CREATE TABLE IF NOT EXISTS public.logs_sistema (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acao TEXT NOT NULL,
    detalhes TEXT,
    tipo TEXT, -- 'info', 'sucesso', 'erro', 'aviso'
    data_hora TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

