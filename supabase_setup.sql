-- Função auxiliar para verificar se é admin (pela coluna role)
CREATE OR REPLACE FUNCTION public.eh_admin(usuario_id BIGINT)
RETURNS boolean AS $$
  SELECT EXISTS (SELECT 1 FROM public.users WHERE id = usuario_id AND role = 'ADMIN');
$$ LANGUAGE sql STABLE;

-- Políticas para Categorias (Leitura pública, escrita só admin)
DROP POLICY IF EXISTS "Categorias visíveis para todos" ON public.categories;
